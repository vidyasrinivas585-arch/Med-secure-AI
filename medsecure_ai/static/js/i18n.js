/* =========================================================
   Translate exact text
   ========================================================= */

function translateText(text) {

    if (!text) return text;

    const trimmed = text.trim();

    if (translations[trimmed]) {
        return text.replace(
            trimmed,
            translations[trimmed]
        );
    }

    return text;
}


/* =========================================================
   Translate page
   ========================================================= */

function translatePage() {

    /* ---------- Text Nodes ---------- */

    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode: function(node) {

                const parent = node.parentElement;

                if (!parent) {
                    return NodeFilter.FILTER_REJECT;
                }

                const tag = parent.tagName.toLowerCase();

                if (
                    tag === "script" ||
                    tag === "style" ||
                    tag === "code" ||
                    tag === "pre"
                ) {
                    return NodeFilter.FILTER_REJECT;
                }

                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const nodes = [];

    while (walker.nextNode()) {
        nodes.push(walker.currentNode);
    }

    nodes.forEach(function(node) {

        const original = node.textContent;

        if (!original.trim()) {
            return;
        }

        /*
         * Store original English text.
         * This prevents Kannada -> Kannada -> Kannada
         * translation problems.
         */

        if (!node.dataset.i18nOriginal) {
            node.dataset.i18nOriginal = original;
        }

        const sourceText = node.dataset.i18nOriginal;

        const translated = translateText(sourceText);

        node.textContent =
            translated !== sourceText
                ? translated
                : sourceText;
    });


    /* ---------- Placeholder ---------- */

    document
        .querySelectorAll("[placeholder]")
        .forEach(function(el) {

            if (!el.dataset.i18nOriginalPlaceholder) {

                el.dataset.i18nOriginalPlaceholder =
                    el.getAttribute("placeholder");
            }

            const original =
                el.dataset.i18nOriginalPlaceholder;

            if (translations[original]) {

                el.setAttribute(
                    "placeholder",
                    translations[original]
                );

            } else {

                el.setAttribute(
                    "placeholder",
                    original
                );
            }
        });


    /* ---------- Title ---------- */

    document
        .querySelectorAll("[title]")
        .forEach(function(el) {

            if (!el.dataset.i18nOriginalTitle) {

                el.dataset.i18nOriginalTitle =
                    el.getAttribute("title");
            }

            const original =
                el.dataset.i18nOriginalTitle;

            if (translations[original]) {

                el.setAttribute(
                    "title",
                    translations[original]
                );

            } else {

                el.setAttribute(
                    "title",
                    original
                );
            }
        });


    /* ---------- data-i18n ---------- */

    document
        .querySelectorAll("[data-i18n]")
        .forEach(function(el) {

            const key =
                el.getAttribute("data-i18n");

            if (translations[key]) {

                el.textContent =
                    translations[key];

            } else {

                el.textContent = key;
            }
        });
}


/* =========================================================
   Restore English
   ========================================================= */

function restoreEnglish() {

    document
        .querySelectorAll("[data-i18n-original]")
        .forEach(function(el) {

            el.textContent =
                el.dataset.i18nOriginal;
        });

    document
        .querySelectorAll("[data-i18n-original-placeholder]")
        .forEach(function(el) {

            el.setAttribute(
                "placeholder",
                el.dataset.i18nOriginalPlaceholder
            );
        });

    document
        .querySelectorAll("[data-i18n-original-title]")
        .forEach(function(el) {

            el.setAttribute(
                "title",
                el.dataset.i18nOriginalTitle
            );
        });
}


/* =========================================================
   Apply Language
   ========================================================= */

function applyI18n(language = "en") {

    localStorage.setItem(
        "medsecure_language",
        language
    );

    document.documentElement.setAttribute(
        "lang",
        language
    );


    /* ================= ENGLISH ================= */

    if (language === "en") {

        /*
         * Reload page so Jinja/HTML returns to
         * original English text.
         */

        location.reload();

        return;
    }


    /* ================= KANNADA ================= */

    if (language === "kn") {

        setTimeout(function() {

            translatePage();

        }, 50);


        /* Dynamic content observer */

        if (!window.medsecureObserver) {

            window.medsecureObserver =
                new MutationObserver(function(mutations) {

                    let shouldTranslate = false;

                    mutations.forEach(function(mutation) {

                        if (
                            mutation.addedNodes &&
                            mutation.addedNodes.length > 0
                        ) {

                            shouldTranslate = true;

                        }

                    });


                    if (shouldTranslate) {

                        setTimeout(
                            translatePage,
                            10
                        );

                    }

                });


            window.medsecureObserver.observe(
                document.body,
                {
                    childList: true,
                    subtree: true
                }
            );
        }
    }
}


/* =========================================================
   Language Selector
   ========================================================= */

function changeLanguage(language) {

    localStorage.setItem(
        "medsecure_language",
        language
    );

    applyI18n(language);
}


/* =========================================================
   Load Saved Language
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    function() {

        const savedLanguage =
            localStorage.getItem(
                "medsecure_language"
            ) || "en";


        const selector =
            document.getElementById(
                "languageSelector"
            );


        if (selector) {

            selector.value =
                savedLanguage;

        }


        if (savedLanguage === "kn") {

            setTimeout(function() {

                translatePage();

            }, 100);

        }

    }
);